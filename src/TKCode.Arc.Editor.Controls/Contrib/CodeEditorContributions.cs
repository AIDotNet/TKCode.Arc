// The built-in editor features (upstream: the registerEditorContribution / registerEditorAction /
// registerEditorCommand calls that run when editor.all.ts loads the contrib modules; src/vs/editor/browser/
// editorExtensions.ts, commit b57d5c9e, MIT license). Here nothing registers itself: every CodeEditor creates the
// contributions of Contributions and registers the commands of EditorCommands (actions included) into its own
// registries (CodeEditor.Contributions.cs).
//
// ONE LINE PER ENTRY: a feature adds its own line, referring to a static member of its own file under
// Contrib/<Feature>/, e.g.
//     FindController.Description,
//     FindController.StartFindAction,
// Keep each list in upstream's editor.all.ts order where the order matters (contributions are created in list order
// within one instantiation kind; for keybindings with equal weight the later registration wins).

