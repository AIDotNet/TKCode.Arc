internal sealed partial class TextModel
{
    // Used to workaround broken clients that might attempt using a decoration id generated by a different model.
    // It is not globally unique in order to limit it to one character.
    private readonly string _instanceId;
    private int _deltaDecorationCallCnt;
    private int _lastDecorationId;
    private Dictionary<string, IntervalNode> _decorations;
    private DecorationsTrees _decorationsTree;

    private void HandleBeforeFireDecorationsChangedEvent(
        IReadOnlyCollection<int>? affectedInjectedTextLines,
        IReadOnlyCollection<LineHeightChangingDecoration>? affectedLineHeights,
        IReadOnlyCollection<LineFontChangingDecoration>? affectedFontLines)
    {
        // This is called before the decoration changed event is fired.

        if (affectedInjectedTextLines is { Count: > 0 })
        {
            var lineChangeEvents = affectedInjectedTextLines
                .Select(lineNumber => new ModelRawLineChanged(lineNumber, lineNumber))
                .ToList();
            OnDidChangeContentOrInjectedText(new ModelInjectedTextChangedEvent(lineChangeEvents));
        }

        FireOnDidChangeLineHeight(affectedLineHeights);
        FireOnDidChangeFont(affectedFontLines);
    }

    private void FireOnDidChangeLineHeight(IReadOnlyCollection<LineHeightChangingDecoration>? affectedLineHeights)
    {
        if (affectedLineHeights is { Count: > 0 })
        {
            var lineHeightChangeEvent = affectedLineHeights
                .Select(change => new ModelLineHeightChanged(change.OwnerId, change.DecorationId, change.LineNumber, change.LineHeight))
                .ToList();
            _onDidChangeLineHeight.Fire(new ModelLineHeightChangedEvent(lineHeightChangeEvent));
        }
    }

    private void FireOnDidChangeFont(IReadOnlyCollection<LineFontChangingDecoration>? affectedFontLines)
    {
        if (affectedFontLines is { Count: > 0 })
        {
            var fontChangeEvent = affectedFontLines
                .Select(change => new ModelFontChanged(change.OwnerId, change.LineNumber))
                .ToList();
            _onDidChangeFont.Fire(new ModelFontChangedEvent(fontChangeEvent));
        }
    }

    private void OnDidChangeContentOrInjectedText(IModelContentOrInjectedTextChangedEvent e)
    {
        // A view model may unregister itself while handling the event.
        var viewModels = _viewModels.ToArray();
        foreach (var viewModel in viewModels)
        {
            try
            {
                viewModel.OnDidChangeContentOrInjectedText(e);
            }
            catch (Exception error)
            {
                UnexpectedErrors.Report(error);
            }
        }

        foreach (var viewModel in viewModels)
        {
            try
            {
                viewModel.EmitContentChangeEvent(e);
            }
            catch (Exception error)
            {
                UnexpectedErrors.Report(error);
            }
        }
    }

    /// <summary>
    /// Changes decorations through an accessor that is valid only while <paramref name="callback"/> runs; the
    /// decorations event is raised once at the end.
    /// </summary>
    public T? ChangeDecorations<T>(Func<ModelDecorationsChangeAccessor, T> callback, int ownerId = 0)
    {
        AssertNotDisposed();

        try
        {
            _onDidChangeDecorations.BeginDeferredEmit();
            return ChangeDecorationsCore(ownerId, callback);
        }
        finally
        {
            _onDidChangeDecorations.EndDeferredEmit();
        }
    }

    private T? ChangeDecorationsCore<T>(int ownerId, Func<ModelDecorationsChangeAccessor, T> callback)
    {
        var changeAccessor = new ModelDecorationsChangeAccessor(this, ownerId);
        T? result = default;
        try
        {
            result = callback(changeAccessor);
        }
        catch (Exception e)
        {
            UnexpectedErrors.Report(e);
        }

        // Invalidate change accessor
        changeAccessor.Invalidate();
        return result;
    }

    /// <summary>
    /// Removes the decorations <paramref name="oldDecorations"/> and adds <paramref name="newDecorations"/>, reusing
    /// the old nodes; returns the ids of the new decorations.
    /// </summary>
    public string[] DeltaDecorations(
        IReadOnlyList<string>? oldDecorations,
        IReadOnlyList<ModelDeltaDecoration> newDecorations,
        int ownerId = 0)
    {
        AssertNotDisposed();
        oldDecorations ??= [];
        if (oldDecorations.Count == 0 && newDecorations.Count == 0)
        {
            // nothing to do
            return [];
        }

        try
        {
            _deltaDecorationCallCnt++;
            if (_deltaDecorationCallCnt > 1)
            {
                UnexpectedErrors.Report(new InvalidOperationException(
                    "Invoking deltaDecorations recursively could lead to leaking decorations."));
            }

            _onDidChangeDecorations.BeginDeferredEmit();
            return DeltaDecorationsImpl(ownerId, oldDecorations, newDecorations);
        }
        finally
        {
            _onDidChangeDecorations.EndDeferredEmit();
            _deltaDecorationCallCnt--;
        }
    }

    internal TextRange? GetTrackedRange(string id) => GetDecorationRange(id);

    /// <summary>
    /// Adds, moves or (with a null range) removes a tracked range: a decoration with no look whose edges move with the
    /// edits by <paramref name="newStickiness"/>. Returns its id, or null when it was removed.
    /// </summary>
    internal string? SetTrackedRange(string? id, TextRange? newRange, TrackedRangeStickiness newStickiness)
    {
        var node = id is not null ? _decorations.GetValueOrDefault(id) : null;

        if (node is null)
        {
            if (newRange is null)
            {
                // node doesn't exist, the request is to delete => nothing to do
                return null;
            }

            // node doesn't exist, the request is to set => add the tracked range
            return DeltaDecorationsImpl(
                0,
                [],
                [new ModelDeltaDecoration(newRange.Value, ModelDecorationOptions.TrackedRangeOptions[(int)newStickiness])],
                true)[0];
        }

        if (newRange is null)
        {
            // node exists, the request is to delete => delete node
            _decorationsTree.Delete(node);
            _decorations.Remove(node.Id!);
            return null;
        }

        // node exists, the request is to set => change the tracked range and its options
        var range = ValidateRangeRelaxedNoAllocations(newRange.Value);
        var startOffset = _buffer.GetOffsetAt(range.StartLineNumber, range.StartColumn);
        var endOffset = _buffer.GetOffsetAt(range.EndLineNumber, range.EndColumn);
        _decorationsTree.Delete(node);
        node.Reset(GetVersionId(), startOffset, endOffset, range);
        node.SetOptions(ModelDecorationOptions.TrackedRangeOptions[(int)newStickiness]);
        _decorationsTree.Insert(node);
        return node.Id;
    }

    public void RemoveAllDecorationsWithOwnerId(int ownerId)
    {
        if (_isDisposed)
        {
            return;
        }

        var nodes = _decorationsTree.CollectNodesFromOwner(ownerId);
        for (int i = 0, len = nodes.Count; i < len; i++)
        {
            var node = nodes[i];

            _decorationsTree.Delete(node);
            _decorations.Remove(node.Id!);
        }
    }

    public ModelDecorationOptions? GetDecorationOptions(string decorationId) =>
        _decorations.TryGetValue(decorationId, out var node) ? node.Options : null;

    public TextRange? GetDecorationRange(string decorationId) =>
        _decorations.TryGetValue(decorationId, out var node) ? _decorationsTree.GetNodeRange(this, node) : null;

    public List<ModelDecoration> GetLineDecorations(
        int lineNumber,
        int ownerId = 0,
        bool filterOutValidation = false,
        bool filterFontDecorations = false)
    {
        if (lineNumber < 1 || lineNumber > GetLineCount())
        {
            return [];
        }

        return GetLinesDecorations(lineNumber, lineNumber, ownerId, filterOutValidation, filterFontDecorations);
    }

    public List<ModelDecoration> GetLinesDecorations(
        int startLineNumber,
        int endLineNumber,
        int ownerId = 0,
        bool filterOutValidation = false,
        bool filterFontDecorations = false,
        bool onlyMarginDecorations = false)
    {
        var lineCount = GetLineCount();
        startLineNumber = Math.Min(lineCount, Math.Max(1, startLineNumber));
        endLineNumber = Math.Min(lineCount, Math.Max(1, endLineNumber));
        var endColumn = GetLineMaxColumn(endLineNumber);
        var range = new TextRange(startLineNumber, 1, endLineNumber, endColumn);

        var decorations = GetDecorationsInRangeCore(range, ownerId, filterOutValidation, filterFontDecorations, onlyMarginDecorations);
        if (BracketDecorationProvider is { } provider)
        {
            decorations.AddRange(provider.GetDecorationsInRange(range));
        }

        return decorations;
    }

    public List<ModelDecoration> GetDecorationsInRange(
        TextRange range,
        int ownerId = 0,
        bool filterOutValidation = false,
        bool filterFontDecorations = false,
        bool onlyMinimapDecorations = false,
        bool onlyMarginDecorations = false)
    {
        var validatedRange = ValidateRange(range);
        var decorations = GetDecorationsInRangeCore(validatedRange, ownerId, filterOutValidation, filterFontDecorations, onlyMarginDecorations);
        if (BracketDecorationProvider is { } provider)
        {
            decorations.AddRange(provider.GetDecorationsInRange(validatedRange, onlyMinimapDecorations));
        }

        return decorations;
    }

