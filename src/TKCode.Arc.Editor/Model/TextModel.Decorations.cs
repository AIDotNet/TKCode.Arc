    public List<LineInjectedText> GetLineInjectedText(int lineNumber, int ownerId = 0)
    {
        var startOffset = _buffer.GetOffsetAt(lineNumber, 1);
        var endOffset = startOffset + _buffer.GetLineLength(lineNumber);

        var result = _decorationsTree.GetInjectedTextInInterval(this, startOffset, endOffset, ownerId);
        return LineInjectedText.FromDecorations(result).Where(t => t.LineNumber == lineNumber).ToList();
    }

    public List<ModelDecoration> GetFontDecorationsInRange(TextRange range, int ownerId = 0)
    {
        var startOffset = _buffer.GetOffsetAt(range.StartLineNumber, range.StartColumn);
        var endOffset = _buffer.GetOffsetAt(range.EndLineNumber, range.EndColumn);
        return _decorationsTree.GetFontDecorationsInInterval(this, startOffset, endOffset, ownerId);
    }

    public List<ModelDecoration> GetAllDecorations(int ownerId = 0, bool filterOutValidation = false, bool filterFontDecorations = false)
    {
        var result = _decorationsTree.GetAll(this, ownerId, filterOutValidation, filterFontDecorations, false, false);
        if (BracketDecorationProvider is { } provider)
        {
            result.AddRange(provider.GetAllDecorations());
        }

        return result;
    }

    public List<ModelDecoration> GetAllMarginDecorations(int ownerId = 0) =>
