    private List<ModelDecoration> GetDecorationsInRangeCore(
        TextRange filterRange,
        int filterOwnerId,
        bool filterOutValidation,
        bool filterFontDecorations,
        bool onlyMarginDecorations)
    {
        var startOffset = _buffer.GetOffsetAt(filterRange.StartLineNumber, filterRange.StartColumn);
        var endOffset = _buffer.GetOffsetAt(filterRange.EndLineNumber, filterRange.EndColumn);
        return _decorationsTree.GetAllInInterval(
            this, startOffset, endOffset, filterOwnerId, filterOutValidation, filterFontDecorations, onlyMarginDecorations);
    }

    /// <summary>The range between two offsets.</summary>
    public TextRange GetRangeAt(int start, int end) => _buffer.GetRangeAt(start, end - start);

    private void ChangeDecorationImpl(int ownerId, string decorationId, TextRange rawRange)
    {
        if (!_decorations.TryGetValue(decorationId, out var node))
        {
            return;
        }

        var options = node.Options!;
        if (options.After is not null)
        {
            var oldRange = GetDecorationRange(decorationId)!.Value;
            _onDidChangeDecorations.RecordLineAffectedByInjectedText(oldRange.EndLineNumber);
        }

        if (options.Before is not null)
        {
            var oldRange = GetDecorationRange(decorationId)!.Value;
            _onDidChangeDecorations.RecordLineAffectedByInjectedText(oldRange.StartLineNumber);
        }

        if (options.LineHeight is not null)
        {
            var oldRange = GetDecorationRange(decorationId)!.Value;
            _onDidChangeDecorations.RecordLineAffectedByLineHeightChange(ownerId, decorationId, oldRange.StartLineNumber, null);
        }

        if (options.AffectsFont)
        {
            var oldRange = GetDecorationRange(decorationId)!.Value;
            _onDidChangeDecorations.RecordLineAffectedByFontChange(ownerId, node.Id!, oldRange.StartLineNumber);
        }

        var range = ValidateRangeRelaxedNoAllocations(rawRange);
        var startOffset = _buffer.GetOffsetAt(range.StartLineNumber, range.StartColumn);
        var endOffset = _buffer.GetOffsetAt(range.EndLineNumber, range.EndColumn);

        _decorationsTree.Delete(node);
        node.Reset(GetVersionId(), startOffset, endOffset, range);
        _decorationsTree.Insert(node);
        _onDidChangeDecorations.CheckAffectedAndFire(options);

        if (options.After is not null)
        {
            _onDidChangeDecorations.RecordLineAffectedByInjectedText(range.EndLineNumber);
        }

        if (options.Before is not null)
        {
            _onDidChangeDecorations.RecordLineAffectedByInjectedText(range.StartLineNumber);
        }

        if (options.LineHeight is not null)
        {
            _onDidChangeDecorations.RecordLineAffectedByLineHeightChange(ownerId, decorationId, range.StartLineNumber, options.LineHeight);
        }

        if (options.AffectsFont)
        {
            _onDidChangeDecorations.RecordLineAffectedByFontChange(ownerId, node.Id!, range.StartLineNumber);
        }
    }

    private void ChangeDecorationOptionsImpl(int ownerId, string decorationId, ModelDecorationOptions options)
    {
        if (!_decorations.TryGetValue(decorationId, out var node))
        {
            return;
        }

        var nodeOptions = node.Options!;
        var nodeWasInOverviewRuler = nodeOptions.OverviewRuler is { Color.IsEmpty: false };
        var nodeIsInOverviewRuler = options.OverviewRuler is { Color.IsEmpty: false };

        _onDidChangeDecorations.CheckAffectedAndFire(nodeOptions);
        _onDidChangeDecorations.CheckAffectedAndFire(options);

        if (nodeOptions.After is not null || options.After is not null)
        {
            var nodeRange = _decorationsTree.GetNodeRange(this, node);
            _onDidChangeDecorations.RecordLineAffectedByInjectedText(nodeRange.EndLineNumber);
        }

        if (nodeOptions.Before is not null || options.Before is not null)
        {
            var nodeRange = _decorationsTree.GetNodeRange(this, node);
            _onDidChangeDecorations.RecordLineAffectedByInjectedText(nodeRange.StartLineNumber);
        }

        if (nodeOptions.LineHeight is not null || options.LineHeight is not null)
        {
            var nodeRange = _decorationsTree.GetNodeRange(this, node);
            _onDidChangeDecorations.RecordLineAffectedByLineHeightChange(ownerId, decorationId, nodeRange.StartLineNumber, options.LineHeight);
        }

        if (nodeOptions.AffectsFont || options.AffectsFont)
        {
            var nodeRange = _decorationsTree.GetNodeRange(this, node);
            _onDidChangeDecorations.RecordLineAffectedByFontChange(ownerId, decorationId, nodeRange.StartLineNumber);
        }

        var movedInOverviewRuler = nodeWasInOverviewRuler != nodeIsInOverviewRuler;
        var changedWhetherInjectedText = DecorationsTrees.IsOptionsInjectedText(options) != DecorationsTrees.IsNodeInjectedText(node);
        if (movedInOverviewRuler || changedWhetherInjectedText)
        {
            _decorationsTree.Delete(node);
            node.SetOptions(options);
            _decorationsTree.Insert(node);
        }
        else
        {
            node.SetOptions(options);
        }
    }

    private string[] DeltaDecorationsImpl(
        int ownerId,
        IReadOnlyList<string> oldDecorationsIds,
        IReadOnlyList<ModelDeltaDecoration> newDecorations,
        bool suppressEvents = false)
    {
        var versionId = GetVersionId();

        var oldDecorationsLen = oldDecorationsIds.Count;
        var oldDecorationIndex = 0;

        var newDecorationsLen = newDecorations.Count;
        var newDecorationIndex = 0;

        _onDidChangeDecorations.BeginDeferredEmit();
        try
        {
            var result = new string[newDecorationsLen];
            while (oldDecorationIndex < oldDecorationsLen || newDecorationIndex < newDecorationsLen)
            {
                IntervalNode? node = null;

                if (oldDecorationIndex < oldDecorationsLen)
                {
                    // (1) get ourselves an old node
                    string decorationId;
                    do
                    {
                        decorationId = oldDecorationsIds[oldDecorationIndex++];
                        node = _decorations.GetValueOrDefault(decorationId);
                    }
                    while (node is null && oldDecorationIndex < oldDecorationsLen);

                    // (2) remove the node from the tree (if it exists)
                    if (node is not null)
                    {
                        var nodeOptions = node.Options!;
                        if (nodeOptions.After is not null)
                        {
                            var nodeRange = _decorationsTree.GetNodeRange(this, node);
                            _onDidChangeDecorations.RecordLineAffectedByInjectedText(nodeRange.EndLineNumber);
                        }

                        if (nodeOptions.Before is not null)
                        {
                            var nodeRange = _decorationsTree.GetNodeRange(this, node);
                            _onDidChangeDecorations.RecordLineAffectedByInjectedText(nodeRange.StartLineNumber);
                        }

                        if (nodeOptions.LineHeight is not null)
                        {
                            var nodeRange = _decorationsTree.GetNodeRange(this, node);
                            _onDidChangeDecorations.RecordLineAffectedByLineHeightChange(ownerId, decorationId, nodeRange.StartLineNumber, null);
                        }

                        if (nodeOptions.AffectsFont)
                        {
                            var nodeRange = _decorationsTree.GetNodeRange(this, node);
                            _onDidChangeDecorations.RecordLineAffectedByFontChange(ownerId, decorationId, nodeRange.StartLineNumber);
                        }

                        _decorationsTree.Delete(node);

                        if (!suppressEvents)
                        {
                            _onDidChangeDecorations.CheckAffectedAndFire(nodeOptions);
                        }
                    }
                }

                if (newDecorationIndex < newDecorationsLen)
                {
                    // (3) create a new node if necessary
                    if (node is null)
                    {
                        var internalDecorationId = ++_lastDecorationId;
                        var decorationId = $"{_instanceId};{internalDecorationId}";
                        node = new IntervalNode(decorationId, 0, 0);
                        _decorations[decorationId] = node;
                    }

                    // (4) initialize node
                    var newDecoration = newDecorations[newDecorationIndex];
                    var range = ValidateRangeRelaxedNoAllocations(newDecoration.Range);
                    var options = newDecoration.Options;
                    var startOffset = _buffer.GetOffsetAt(range.StartLineNumber, range.StartColumn);
                    var endOffset = _buffer.GetOffsetAt(range.EndLineNumber, range.EndColumn);

                    node.OwnerId = ownerId;
                    node.Reset(versionId, startOffset, endOffset, range);
                    node.SetOptions(options);

                    if (options.After is not null)
                    {
                        _onDidChangeDecorations.RecordLineAffectedByInjectedText(range.EndLineNumber);
                    }

                    if (options.Before is not null)
                    {
                        _onDidChangeDecorations.RecordLineAffectedByInjectedText(range.StartLineNumber);
                    }

                    if (options.LineHeight is not null)
                    {
                        _onDidChangeDecorations.RecordLineAffectedByLineHeightChange(ownerId, node.Id!, range.StartLineNumber, options.LineHeight);
                    }

                    if (options.AffectsFont)
                    {
                        _onDidChangeDecorations.RecordLineAffectedByFontChange(ownerId, node.Id!, range.StartLineNumber);
                    }

                    if (!suppressEvents)
                    {
                        _onDidChangeDecorations.CheckAffectedAndFire(options);
                    }

                    _decorationsTree.Insert(node);

                    result[newDecorationIndex] = node.Id!;

                    newDecorationIndex++;
                }
                else if (node is not null)
                {
                    _decorations.Remove(node.Id!);
                }
            }

            return result;
        }
        finally
        {
            _onDidChangeDecorations.EndDeferredEmit();
        }
    }

    /// <summary>
    /// Changes the decorations of one owner during <see cref="ChangeDecorations{T}"/> (Monaco's
    /// <c>IModelDecorationsChangeAccessor</c>). Calls after the callback returned throw.
    /// </summary>
    internal sealed class ModelDecorationsChangeAccessor
    {
        private readonly TextModel _model;
        private readonly int _ownerId;
        private bool _isValid = true;

        internal ModelDecorationsChangeAccessor(TextModel model, int ownerId)
        {
            _model = model;
            _ownerId = ownerId;
        }

        internal void Invalidate() => _isValid = false;

        private void AssertValid()
        {
            if (!_isValid)
            {
                throw new InvalidOperationException("Invalid change accessor");
            }
        }

        public string AddDecoration(TextRange range, ModelDecorationOptions options)
        {
            AssertValid();
            return _model.DeltaDecorationsImpl(_ownerId, [], [new ModelDeltaDecoration(range, options)])[0];
        }

        public void ChangeDecoration(string id, TextRange newRange)
        {
            AssertValid();
            _model.ChangeDecorationImpl(_ownerId, id, newRange);
        }

        public void ChangeDecorationOptions(string id, ModelDecorationOptions options)
        {
            AssertValid();
            _model.ChangeDecorationOptionsImpl(_ownerId, id, options);
        }

        public void RemoveDecoration(string id)
        {
            AssertValid();
            _model.DeltaDecorationsImpl(_ownerId, [id], []);
        }

        public string[] DeltaDecorations(IReadOnlyList<string> oldDecorations, IReadOnlyList<ModelDeltaDecoration> newDecorations)
        {
            AssertValid();
            if (oldDecorations.Count == 0 && newDecorations.Count == 0)
            {
                // nothing to do
                return [];
            }

            return _model.DeltaDecorationsImpl(_ownerId, oldDecorations, newDecorations);
        }
    }
