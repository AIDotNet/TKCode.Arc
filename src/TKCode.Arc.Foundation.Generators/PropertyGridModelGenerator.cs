using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace TKCode.Arc.Foundation.Generators
{
    /// <summary>
    /// Registers every <c>[PropertyGridModel]</c> type with <c>TKCode.Arc.PropertyGridTypes</c> from a module initializer:
    /// a descriptor per public property, with typed get and set delegates and the System.ComponentModel and
    /// <c>[PropertyGridOptions]</c> metadata, so a PropertyGrid edits the type without reflection (AOT and trimming safe).
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class PropertyGridModelGenerator : IIncrementalGenerator
    {
        internal const string AttributeName = "TKCode.Arc.PropertyGridModelAttribute";
        private const string OptionsAttributeName = "TKCode.Arc.PropertyGridOptionsAttribute";
        private const string ModuleInitializerName = "System.Runtime.CompilerServices.ModuleInitializerAttribute";

        /// <inheritdoc />
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax,
                static (ctx, cancellation) => Build((INamedTypeSymbol)ctx.TargetSymbol, ctx.SemanticModel.Compilation, cancellation));

            context.RegisterSourceOutput(models, static (spc, model) =>
            {
                foreach (var diagnostic in model.Diagnostics)
                {
                    spc.ReportDiagnostic(diagnostic.ToDiagnostic());
                }
                if (model.Code is not null)
                {
                    spc.AddSource(model.HintName, SourceText.From(model.Code, Encoding.UTF8));
                }
            });
        }

        internal static PropertyGridModel Build(INamedTypeSymbol type, Compilation compilation, System.Threading.CancellationToken cancellation)
        {
            var location = type.Locations.FirstOrDefault();
            var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var hint = "PropertyGrid." + SafeName(type.ToDisplayString()) + ".g.cs";
            if (type.IsGenericType || type.IsStatic)
            {
                return PropertyGridModel.Failed(hint, DiagnosticInfo.Create(Diagnostics.PropertyGridModelShape, location, type.Name));
            }
            if (!IsAccessible(type))
            {
                return PropertyGridModel.Failed(hint, DiagnosticInfo.Create(Diagnostics.PropertyGridModelAccess, location, type.Name));
            }
            if (compilation.GetTypeByMetadataName(ModuleInitializerName) is null)
            {
                return PropertyGridModel.Failed(hint, DiagnosticInfo.Create(Diagnostics.PropertyGridNoModuleInitializer, location, type.Name));
            }

            var properties = CollectProperties(type);
            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("#pragma warning disable CS0612, CS0618, CA2255");
            builder.AppendLine();
            builder.Append("internal static class __ArcPropertyGrid_").Append(SafeName(type.ToDisplayString()).Replace('.', '_')).AppendLine();
            builder.AppendLine("{");
            builder.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
            builder.AppendLine("    internal static void Register()");
            builder.AppendLine("    {");
            builder.Append("        global::TKCode.Arc.PropertyGridTypes.Register(typeof(").Append(name).AppendLine("), static () =>");
            builder.Append("            new global::TKCode.Arc.PropertyGridTypeInfo(typeof(").Append(name).AppendLine("), new global::TKCode.Arc.PropertyGridProperty[]");
            builder.AppendLine("            {");
            foreach (var property in properties)
            {
                cancellation.ThrowIfCancellationRequested();
                EmitProperty(builder, type, name, property);
            }
            builder.AppendLine("            }));");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return new PropertyGridModel(hint, builder.ToString(), EquatableArray<DiagnosticInfo>.Empty);
        }

        /// <summary>Public instance properties with a public getter, base types first, the most derived one of each name.</summary>
        private static List<IPropertySymbol> CollectProperties(INamedTypeSymbol type)
        {
            var chain = new List<INamedTypeSymbol>();
            for (var current = type; current is not null && current.SpecialType != SpecialType.System_Object
                 && current.SpecialType != SpecialType.System_ValueType; current = current.BaseType)
            {
                chain.Insert(0, current);
            }
            var byName = new Dictionary<string, int>(StringComparer.Ordinal);
            var list = new List<IPropertySymbol>();
            foreach (var declaring in chain)
            {
                foreach (var member in declaring.GetMembers())
                {
                    if (member is not IPropertySymbol property || property.IsStatic || property.IsIndexer
                        || property.DeclaredAccessibility != Accessibility.Public || property.GetMethod is null
                        || property.GetMethod.DeclaredAccessibility != Accessibility.Public || property.ReturnsByRef
                        || property.ReturnsByRefReadonly || property.Type.IsRefLikeType || property.Type is IPointerTypeSymbol
                        || property.Type is IFunctionPointerTypeSymbol || !IsAccessible(property.Type)
                        || property.ExplicitInterfaceImplementations.Length > 0 || IsHidden(property))
                    {
                        continue;
                    }
                    if (byName.TryGetValue(property.Name, out var index))
                    {
                        list[index] = property;
                    }
                    else
                    {
                        byName.Add(property.Name, list.Count);
                        list.Add(property);
                    }
                }
            }
            return list;
        }

        private static bool IsHidden(IPropertySymbol property)
        {
            foreach (var attribute in AttributesOf(property))
            {
                if (attribute.AttributeClass?.ToDisplayString() == "System.ComponentModel.BrowsableAttribute"
                    && attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is false)
                {
                    return true;
                }
            }
            return false;
        }

        /// <summary>Attributes of the property and of the properties it overrides.</summary>
        private static IEnumerable<AttributeData> AttributesOf(IPropertySymbol property)
        {
            for (var current = property; current is not null; current = current.OverriddenProperty)
            {
                foreach (var attribute in current.GetAttributes())
                {
                    yield return attribute;
                }
            }
        }

        private static void EmitProperty(StringBuilder builder, INamedTypeSymbol owner, string ownerName, IPropertySymbol property)
        {
            var valueType = property.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated);
            var valueName = valueType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var canWrite = property.SetMethod is { } setter && setter.DeclaredAccessibility == Accessibility.Public && !setter.IsInitOnly
                           && !(owner.IsValueType && owner.IsReadOnly);

            builder.Append("                new global::TKCode.Arc.PropertyGridProperty(").Append(Literal(property.Name))
                .Append(", typeof(").Append(valueName).Append("), static o => ((").Append(ownerName).Append(")o).")
                .Append(property.Name).Append(", ");
            if (!canWrite)
            {
                builder.Append("null");
            }
            else if (owner.IsValueType)
            {
                builder.Append("static (o, v) => { var t = (").Append(ownerName).Append(")o; t.").Append(property.Name)
                    .Append(" = (").Append(valueName).Append(")v!; return t; }");
            }
            else
            {
                builder.Append("static (o, v) => { ((").Append(ownerName).Append(")o).").Append(property.Name)
                    .Append(" = (").Append(valueName).Append(")v!; return o; }");
            }
            builder.AppendLine(")");
            builder.AppendLine("                {");

            string? displayName = null, category = null, description = null;
            var readOnly = false;
            AttributeData? options = null;
            foreach (var attribute in AttributesOf(property).Reverse())
            {
                var attributeName = attribute.AttributeClass?.ToDisplayString();
                var first = attribute.ConstructorArguments.Length > 0 ? attribute.ConstructorArguments[0].Value : null;
                switch (attributeName)
                {
                    case "System.ComponentModel.DisplayNameAttribute" when first is string text:
                        displayName = text;
                        break;
                    case "System.ComponentModel.CategoryAttribute" when first is string text:
                        category = text;
                        break;
                    case "System.ComponentModel.DescriptionAttribute" when first is string text:
                        description = text;
                        break;
                    case "System.ComponentModel.ReadOnlyAttribute" when first is bool flag:
                        readOnly = flag;
                        break;
                    case "System.ComponentModel.DataAnnotations.DisplayAttribute":
                        foreach (var named in attribute.NamedArguments)
                        {
                            if (named.Key == "Name" && named.Value.Value is string displayText)
                            {
                                displayName ??= displayText;
                            }
                            else if (named.Key == "GroupName" && named.Value.Value is string group)
                            {
                                category ??= group;
                            }
                            else if (named.Key == "Description" && named.Value.Value is string help)
                            {
                                description ??= help;
                            }
                        }
                        break;
                    case OptionsAttributeName:
                        options = attribute;
                        break;
                }
            }
            if (options is not null)
            {
                EmitOptions(builder, options);
            }
            if (displayName is not null)
            {
                builder.Append("                    DisplayName = ").Append(Literal(displayName)).AppendLine(",");
            }
            if (category is not null)
            {
                builder.Append("                    Category = ").Append(Literal(category)).AppendLine(",");
            }
            if (description is not null)
            {
                builder.Append("                    Description = ").Append(Literal(description)).AppendLine(",");
            }
            if (readOnly)
            {
                builder.AppendLine("                    IsReadOnly = true,");
            }
            EmitChoices(builder, valueType);
            EmitElements(builder, valueType);
            builder.AppendLine("                },");
        }

        private static void EmitOptions(StringBuilder builder, AttributeData attribute)
        {
            foreach (var named in attribute.NamedArguments)
            {
                var value = named.Value.Value;
                switch (named.Key)
                {
                    case "Order" when value is int order:
                        builder.Append("                    Order = ").Append(order.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
                        break;
                    case "EditorKey" when value is string key:
                        builder.Append("                    EditorKey = ").Append(Literal(key)).AppendLine(",");
                        break;
                    case "Classes" when value is string classes:
                        builder.Append("                    Classes = ").Append(Literal(classes)).AppendLine(",");
                        break;
                    case "Minimum" or "Maximum" or "Step" when value is double number && !double.IsNaN(number) && !double.IsInfinity(number):
                        builder.Append("                    ").Append(named.Key).Append(" = ")
                            .Append(number.ToString("R", CultureInfo.InvariantCulture)).AppendLine("d,");
                        break;
                    case "FractionDigits" when value is int digits && digits >= 0:
                        builder.Append("                    FractionDigits = ").Append(digits.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
                        break;
                    case "Expand" when value is int expand && expand != 0:
                        builder.Append("                    Expand = (global::TKCode.Arc.PropertyGridExpand)")
                            .Append(expand.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
                        break;
                }
            }
        }

        /// <summary>An enum gets its members as choices; [Description] or [Display(Name)] on a member is its text.</summary>
        private static void EmitChoices(StringBuilder builder, ITypeSymbol valueType)
        {
            var enumType = valueType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable
                ? nullable.TypeArguments[0]
                : valueType;
            if (enumType.TypeKind != TypeKind.Enum || !IsAccessible(enumType))
            {
                return;
            }
            var enumName = enumType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            builder.AppendLine("                    Choices = new global::TKCode.Arc.PropertyGridChoice[]");
            builder.AppendLine("                    {");
            var seen = new HashSet<object?>();
            foreach (var member in enumType.GetMembers().OfType<IFieldSymbol>())
            {
                if (!member.HasConstantValue || !seen.Add(member.ConstantValue) || IsHiddenField(member))
                {
                    continue;
                }
                builder.Append("                        new global::TKCode.Arc.PropertyGridChoice(").Append(enumName).Append('.')
                    .Append(member.Name).Append(", ").Append(Literal(TextOf(member))).AppendLine("),");
            }
            builder.AppendLine("                    },");
        }

        private static bool IsHiddenField(IFieldSymbol field)
            => field.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.ComponentModel.BrowsableAttribute"
                                              && a.ConstructorArguments.Length == 1 && a.ConstructorArguments[0].Value is false);

        private static string TextOf(IFieldSymbol field)
        {
            foreach (var attribute in field.GetAttributes())
            {
                var name = attribute.AttributeClass?.ToDisplayString();
                if (name == "System.ComponentModel.DescriptionAttribute" && attribute.ConstructorArguments.Length == 1
                    && attribute.ConstructorArguments[0].Value is string description)
                {
                    return description;
                }
                if (name == "System.ComponentModel.DataAnnotations.DisplayAttribute")
                {
                    foreach (var named in attribute.NamedArguments)
                    {
                        if (named.Key == "Name" && named.Value.Value is string display)
                        {
                            return display;
                        }
                    }
                }
            }
            return field.Name;
        }

        /// <summary>A list gets its item type, and a factory for the add button when an item can be created.</summary>
        private static void EmitElements(StringBuilder builder, ITypeSymbol valueType)
        {
            if (valueType.SpecialType == SpecialType.System_String)
            {
                return;
            }
            ITypeSymbol? element = null;
            var growable = false;
            if (valueType is IArrayTypeSymbol array)
            {
                element = array.ElementType;
            }
            else
            {
                var interfaces = valueType is INamedTypeSymbol { TypeKind: TypeKind.Interface } self
                    ? self.AllInterfaces.Add(self)
                    : valueType.AllInterfaces;
                foreach (var candidate in interfaces)
                {
                    var definition = candidate.OriginalDefinition.ToDisplayString();
                    if (definition is "System.Collections.Generic.IList<T>" or "System.Collections.Generic.IReadOnlyList<T>")
                    {
                        element = candidate.TypeArguments[0];
                        growable |= definition == "System.Collections.Generic.IList<T>";
                    }
                }
            }
            if (element is null || !IsAccessible(element))
            {
                return;
            }
            var elementType = element.WithNullableAnnotation(NullableAnnotation.NotAnnotated);
            var elementName = elementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            builder.Append("                    ElementType = typeof(").Append(elementName).AppendLine("),");
            if (!growable)
            {
                return;
            }
            string? factory = null;
            if (elementType.SpecialType == SpecialType.System_String)
            {
                factory = "static () => string.Empty";
            }
            else if (elementType.IsValueType)
            {
                factory = "static () => default(" + elementName + ")";
            }
            else if (elementType is INamedTypeSymbol { IsAbstract: false, TypeKind: TypeKind.Class } named
                     && named.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public))
            {
                factory = "static () => new " + elementName + "()";
            }
            if (factory is not null)
            {
                builder.Append("                    CreateElement = ").Append(factory).AppendLine(",");
            }
        }

        private static bool IsAccessible(ITypeSymbol type)
        {
            switch (type)
            {
                case IArrayTypeSymbol array:
                    return IsAccessible(array.ElementType);
                case ITypeParameterSymbol:
                    return false;
                case INamedTypeSymbol named:
                    for (var current = named; current is not null; current = current.ContainingType)
                    {
                        if (current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
                        {
                            return false;
                        }
                    }
                    return named.TypeArguments.All(IsAccessible);
                default:
                    return false;
            }
        }

        private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

        private static string SafeName(string name)
        {
            var builder = new StringBuilder(name.Length);
            foreach (var c in name)
            {
                builder.Append(char.IsLetterOrDigit(c) || c == '.' || c == '_' ? c : '_');
            }
            return builder.ToString();
        }
    }

    /// <summary>The generated registration of one type (the code is the cache key, so edits elsewhere cost nothing).</summary>
    internal sealed class PropertyGridModel : IEquatable<PropertyGridModel>
    {
        public PropertyGridModel(string hintName, string? code, EquatableArray<DiagnosticInfo> diagnostics)
        {
            HintName = hintName;
            Code = code;
            Diagnostics = diagnostics;
        }

        public string HintName { get; }
        public string? Code { get; }
        public EquatableArray<DiagnosticInfo> Diagnostics { get; }

        public static PropertyGridModel Failed(string hintName, DiagnosticInfo diagnostic)
            => new PropertyGridModel(hintName, null, new EquatableArray<DiagnosticInfo>(ImmutableArray.Create(diagnostic)));

        public bool Equals(PropertyGridModel? other)
            => other is not null && HintName == other.HintName && Code == other.Code && Diagnostics.Equals(other.Diagnostics);

        public override bool Equals(object? obj) => Equals(obj as PropertyGridModel);

        public override int GetHashCode() => HintName.GetHashCode();
    }
}
