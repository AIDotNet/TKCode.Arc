using System.Collections.Generic;
using System.Text;

namespace TKCode.Arc.Foundation.Generators
{
    /// <summary>Writes theme dictionary classes and the per-assembly asset table.</summary>
    internal static class ThemeEmitter
    {
        public static string EmitDictionaryClass(ThemeFile file, string className)
        {
            var dot = className.LastIndexOf('.');
            var ns = dot > 0 ? className.Substring(0, dot) : null;
            var name = dot > 0 ? className.Substring(dot + 1) : className;
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated by TKCode.Arc.Foundation.Generators />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            var indent = string.Empty;
            if (ns is not null)
            {
                sb.Append("namespace ").AppendLine(ns);
                sb.AppendLine("{");
                indent = "    ";
            }
            sb.Append(indent).Append("/// <summary>The compiled dictionary of <c>").Append(file.RelativePath).AppendLine("</c>.</summary>");
            sb.Append(indent).Append(file.IsPublic ? "public" : "internal").Append(" partial class ").Append(name)
              .AppendLine(" : global::Avalonia.Controls.ResourceDictionary");
            sb.Append(indent).AppendLine("{");
            sb.Append(indent).AppendLine("    /// <summary>Builds the dictionary from its compiled XAML (no parsing, no URI lookup).</summary>");
            sb.Append(indent).Append("    public ").Append(name).AppendLine("()");
            sb.Append(indent).AppendLine("    {");
            // Avalonia's XAML compiler rewrites this call into the compiled populate method of the x:Class.
            sb.Append(indent).AppendLine("        global::Avalonia.Markup.Xaml.AvaloniaXamlLoader.Load(this);");
            sb.Append(indent).AppendLine("    }");
            sb.Append(indent).AppendLine("}");
            if (ns is not null)
            {
                sb.AppendLine("}");
            }
            return sb.ToString();
        }

        public static string EmitAssets(string assemblyName, List<TokenModel> tokens,
                                        List<(ThemeFile File, string ClassName, List<string> Keys)> assets,
                                        List<string> catalogs)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated by TKCode.Arc.Foundation.Generators />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.Append("namespace TKCode.Arc.Generated.").AppendLine(Identifier(assemblyName));
            sb.AppendLine("{");
            sb.Append("    /// <summary>Token identities and control-theme files of ").Append(assemblyName).AppendLine(", for the package registration.</summary>");
            sb.AppendLine("    internal static class ArcGeneratedAssets");
            sb.AppendLine("    {");
            sb.AppendLine("        /// <summary>The assembly name, the default package id.</summary>");
            sb.Append("        public const string PackageId = \"").Append(assemblyName).AppendLine("\";");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>The token identities declared in this assembly.</summary>");
            sb.AppendLine("        public static readonly global::TKCode.Arc.ArcTokenDescriptor[] Tokens = new global::TKCode.Arc.ArcTokenDescriptor[]");
            sb.AppendLine("        {");
            foreach (var token in tokens)
            {
                sb.Append("            global::").Append(token.TokensNamespace).Append('.').Append(token.Stem).AppendLine("Tokens.Descriptor,");
            }
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine("        /// <summary>The control-theme files of this assembly; each is instantiated on first lookup of one of its keys.</summary>");
            sb.AppendLine("        public static readonly global::TKCode.Arc.ArcThemeAsset[] Themes = new global::TKCode.Arc.ArcThemeAsset[]");
            sb.AppendLine("        {");
            foreach (var (file, className, keys) in assets)
            {
                sb.Append("            new global::TKCode.Arc.ArcThemeAsset(\"").Append(assemblyName).Append(':').Append(file.RelativePath)
                  .Append("\", new object[] { ").Append(string.Join(", ", keys)).Append(" }, static () => new global::")
                  .Append(className).AppendLine("()),");
            }
            sb.AppendLine("        };");
            sb.AppendLine();
            // Language catalogs (only when there are any, so assemblies without catalogs generate what they did before).
            if (catalogs.Count > 0)
            {
                sb.AppendLine("        /// <summary>The language catalogs of this assembly.</summary>");
                sb.AppendLine("        public static readonly global::TKCode.Arc.Localization.ArcLanguageCatalog[] Languages = new global::TKCode.Arc.Localization.ArcLanguageCatalog[]");
                sb.AppendLine("        {");
                foreach (var catalog in catalogs)
                {
                    sb.Append("            ").Append(catalog).AppendLine(".Catalog,");
                }
                sb.AppendLine("        };");
                sb.AppendLine();
            }
            sb.Append("        /// <summary>Adds this assembly's tokens").Append(catalogs.Count > 0 ? ", theme files and language catalogs" : " and theme files")
              .AppendLine(" to <paramref name=\"package\"/>.</summary>");
            sb.AppendLine("        public static global::TKCode.Arc.ArcPackageBuilder AddTo(global::TKCode.Arc.ArcPackageBuilder package)");
            sb.Append("            => package.AddTokens(Tokens).AddThemes(Themes)").Append(catalogs.Count > 0 ? ".AddLanguages(Languages)" : "").AppendLine(";");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string Identifier(string assemblyName)
        {
            var sb = new StringBuilder();
            foreach (var c in assemblyName)
            {
                if (char.IsLetterOrDigit(c) || c == '_')
                {
                    sb.Append(c);
                }
            }
            if (sb.Length == 0 || char.IsDigit(sb[0]))
            {
                sb.Insert(0, '_');
            }
            return sb.ToString();
        }
    }
}
