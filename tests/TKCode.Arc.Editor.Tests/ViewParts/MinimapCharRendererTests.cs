    private static byte[] GetSampleData()
    {
        var charCode = (int)'d';
        var result = new byte[MinimapCharSheet.SampledCharHeight * MinimapCharSheet.SampledCharWidth * MinimapCharSheet.RgbaChannelsCnt * MinimapCharSheet.CharCount];

        var rowWidth = MinimapCharSheet.SampledCharWidth * MinimapCharSheet.RgbaChannelsCnt * MinimapCharSheet.CharCount;
        var chIndex = charCode - MinimapCharSheet.StartChCode;

        var globalOutputOffset = chIndex * MinimapCharSheet.SampledCharWidth * MinimapCharSheet.RgbaChannelsCnt;
        var inputOffset = 0;
        for (var i = 0; i < MinimapCharSheet.SampledCharHeight; i++)
        {
            var outputOffset = globalOutputOffset;
            for (var j = 0; j < MinimapCharSheet.SampledCharWidth; j++)
            {
                for (var channel = 0; channel < MinimapCharSheet.RgbaChannelsCnt; channel++)
                {
                    result[outputOffset] = s_sampleD[inputOffset];
                    inputOffset++;
                    outputOffset++;
                }
            }

            globalOutputOffset += rowWidth;
        }

        return result;
    }

    private static MinimapImageData CreateImageData(int width, int height, RgbaColor background)
    {
        var imageData = new MinimapImageData(width, height);
        for (var i = 0; i < imageData.Data.Length / 4; i++)
        {
            imageData.Data[(4 * i) + 0] = background.R;
            imageData.Data[(4 * i) + 1] = background.G;
            imageData.Data[(4 * i) + 2] = background.B;
            imageData.Data[(4 * i) + 3] = 255;
        }

        return imageData;
    }

    [Fact]
    public void Letter_d_At_2x()
    {
        var sampleData = GetSampleData();
        var renderer = MinimapCharRendererFactory.CreateFromSampleData(sampleData, 2);

        var background = new RgbaColor(0, 0, 0, 255);
        var color = new RgbaColor(255, 255, 255, 255);
        var imageData = CreateImageData(MinimapCharSheet.BaseCharWidth * 2, MinimapCharSheet.BaseCharHeight * 2, background);
        renderer.RenderChar(imageData, 0, 0, 'd', color, 255, background, 255, 2, false, false);

        imageData.Data.ShouldBe(new byte[]
        {
            0x2D, 0x2D, 0x2D, 0xFF, 0xAC, 0xAC, 0xAC, 0xFF,
            0xC6, 0xC6, 0xC6, 0xFF, 0xC8, 0xC8, 0xC8, 0xFF,
            0xC0, 0xC0, 0xC0, 0xFF, 0xCB, 0xCB, 0xCB, 0xFF,
            0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0xFF,
        });
    }

    [Fact]
    public void Letter_d_At_1x()
    {
        var sampleData = GetSampleData();
        var renderer = MinimapCharRendererFactory.CreateFromSampleData(sampleData, 1);

        var background = new RgbaColor(0, 0, 0, 255);
        var color = new RgbaColor(255, 255, 255, 255);
        var imageData = CreateImageData(MinimapCharSheet.BaseCharWidth, MinimapCharSheet.BaseCharHeight, background);
        renderer.RenderChar(imageData, 0, 0, 'd', color, 255, background, 255, 1, false, false);

        imageData.Data.ShouldBe(new byte[]
        {
            0xCB, 0xCB, 0xCB, 0xFF,
            0x81, 0x81, 0x81, 0xFF,
        });
    }

    [Fact]
    public void The_Prebaked_Sheets_Hold_Every_Character()
    {
        MinimapPreBaked.Get(1)!.Length.ShouldBe(MinimapCharSheet.CharCount * 2);
        MinimapPreBaked.Get(2)!.Length.ShouldBe(MinimapCharSheet.CharCount * 8);
        MinimapPreBaked.Get(3).ShouldBeNull();
        MinimapCharRendererFactory.Create(2).ShouldBeSameAs(MinimapCharRendererFactory.Create(2));
    }

    [Fact]
    public void A_Scale_Without_Prebaked_Data_Enlarges_The_Scale_2_Sheet()
    {
        var background = new RgbaColor(0, 0, 0, 255);
        var color = new RgbaColor(255, 255, 255, 255);
        var at2 = CreateImageData(2, 4, background);
        MinimapCharRendererFactory.Create(2).RenderChar(at2, 0, 0, 'd', color, 255, background, 255, 2, false, false);
        var at4 = CreateImageData(4, 8, background);
        var renderer = MinimapCharRendererFactory.Create(4);
        renderer.Scale.ShouldBe(4);
        renderer.RenderChar(at4, 0, 0, 'd', color, 255, background, 255, 4, false, false);

        // each pixel of the scale 2 character becomes a 2 x 2 block
        for (var y = 0; y < 8; y++)
        {
            for (var x = 0; x < 4; x++)
            {
                at4.Data[((y * 4) + x) * 4].ShouldBe(at2.Data[(((y / 2) * 2) + (x / 2)) * 4]);
            }
        }
    }
