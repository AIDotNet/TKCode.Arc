# Regenerates src/TKCode.Arc.Themes.Corners/CornerTable.g.cs: the ArcDesign radius tokens and every radius control token
# of the Arc packages, with the default value read from the token's source.
# Input: the Foundation generator's *Token.g.cs files under src/*/GeneratedFiles (they exist after a build), the
# *Token.cs sources, and tools/corners/double_radii.json (classification of the double-typed radius tokens).
import collections, glob, json, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.normpath(os.path.join(here, "..", "..", "src"))
catalogs = {
    "TKCode.Arc": "Controls",
    "TKCode.Arc.Blocks": "Blocks",
    "TKCode.Arc.Special": "Special",
    "TKCode.Arc.AdvancedCharts": "AdvancedCharts",
    "TKCode.Arc.Workflow": "Workflow",
}
num = r"-?\d+(?:\.\d+)?"
token_doc = re.compile(r"/// <summary>Token <c>(\w+)</c> \((CornerRadius|double)\)\.</summary>")
identity = re.compile(r'public const string Identity = "([^"]+)";')
classes = json.load(open(os.path.join(here, "double_radii.json"), encoding="utf-8"))
# ArcDesign is generated in Core but listed with the Controls catalog (its own ArcDesign field).
catalog_of = {"TKCode.Arc.Core": "TKCode.Arc"}

found = collections.defaultdict(dict)  # catalog -> {(control, token): is_double}
generated = os.path.join(src, "*", "GeneratedFiles", "TKCode.Arc.Foundation.Generators", "*", "*Token.g.cs")
for path in sorted(glob.glob(generated)):
    package = os.path.relpath(path, src).split(os.sep)[0]
    catalog = catalog_of.get(package, package)
    if catalog not in catalogs:
        continue
    text = open(path, encoding="utf-8-sig").read()
    m = identity.search(text)
    if not m:
        continue
    control = m.group(1)
    if package == "TKCode.Arc.Core" and control != "ArcDesign":
        continue
    for token, clr in token_doc.findall(text):
        is_double = clr == "double"
        if is_double and not re.search(r"Radius|Corner", token):
            continue
        found[catalog][(control, token)] = is_double


errors = []


def read_sources(catalog, control):
    package_dir = os.path.join(src, catalog)
    files = [f for f in glob.glob(os.path.join(package_dir, "**", control + "Token.cs"), recursive=True)
             if os.sep + "obj" + os.sep not in f and os.sep + "GeneratedFiles" + os.sep not in f]
    if control == "ArcDesign":
        files = [os.path.join(src, "TKCode.Arc.Core", "Theme", "ArcDesignToken.cs")]
    return "".join(open(f, encoding="utf-8-sig").read() for f in files)


def default_of(source, token, is_double):
    if is_double:
        values = set(re.findall(r"\b" + token + r"\s*=\s*(" + num + r")\s*;", source))
    else:
        values = set()
        for args in re.findall(r"\b" + token + r"\s*=\s*new\s+CornerRadius\(\s*(" + num + r"(?:\s*,\s*" + num + r"){0,3})\s*\)\s*;", source):
            values.add(",".join(p.strip() for p in args.split(",")))
    return values


def fmt(value):
    return value.replace(" ", "")


out = ["// <auto-generated by tools/corners/generate_corner_table.py; do not edit.",
       "namespace TKCode.Arc.Themes.Corners;", "",
       "internal static class CornerTable", "{"]
for catalog, field in [("TKCode.Arc", "ArcDesign")] + list(catalogs.items()):
    entries = []
    for (control, token), is_double in sorted(found[catalog].items()):
        if (field == "ArcDesign") != (control == "ArcDesign"):
            continue
        kind = "corner"
        if is_double:
            kind = classes.get(control + "." + token)
            if kind is None:
                errors.append(f"{control}.{token}: double radius token is not classified in double_radii.json")
                continue
            if kind != "corner":
                continue
        values = default_of(read_sources(catalog, control), token, is_double)
        if len(values) != 1:
            errors.append(f"{control}.{token}: expected exactly one literal default, found {sorted(values) or 'none'}")
            continue
        entries.append((control, token, fmt(next(iter(values))), is_double))
    out.append(f"    internal static readonly CornerEntry[] {field} =")
    out.append("    [")
    for control, token, default, is_double in entries:
        out.append(f'        new("{control}", "{token}", "{default}", {"true" if is_double else "false"}),')
    out.append("    ];")
    out.append("")
out.append("}")

stale = [k for k in classes if not k.startswith("_") and not any((tuple(k.split(".")) in found[c]) for c in found)]
for k in stale:
    errors.append(f"{k}: listed in double_radii.json but no such token")
if errors:
    print("\n".join(errors), file=sys.stderr)
    sys.exit(1)
open(os.path.join(src, "TKCode.Arc.Themes.Corners", "CornerTable.g.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
