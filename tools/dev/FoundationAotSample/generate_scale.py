#!/usr/bin/env python3
"""Writes the Arc-sized token and theme set of the Foundation AOT sample (design/architecture/foundation.md section 8).

Shape copied from Arc 0.3 (tests/Baselines/tokens): one global identity with 169 tokens and 250 control identities with
18 tokens each (4,669 tokens; Arc has 4,843), types in Arc's proportions (double > Thickness > CornerRadius > Color >
TimeSpan), and 348 theme files with about 30 token references each (Arc: 348 files, ~12,400 references).

Run from this directory: python3 generate_scale.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CONTROL_IDENTITIES = 250
THEME_FILES = 348

GLOBAL = (
    [("Color", f"Color{i}") for i in range(120)]
    + [("double", f"Size{i}") for i in range(20)]
    + [("CornerRadius", f"Radius{i}") for i in range(10)]
    + [("BoxShadows", f"Shadow{i}") for i in range(8)]
    + [("FontFamily", f"Font{i}") for i in range(5)]
    + [("FontWeight", f"Weight{i}") for i in range(2)]
    + [("TimeSpan", f"Duration{i}") for i in range(4)]
)
assert len(GLOBAL) == 169

CONTROL = (
    [("double", f"Size{i}") for i in range(10)]
    + [("Thickness", f"Inset{i}") for i in range(5)]
    + [("CornerRadius", "Radius0"), ("Color", "Tint0"), ("TimeSpan", "Duration0")]
)
assert len(CONTROL) == 18


def value(kind, i, dark):
    if kind == "Color":
        base = (i * 37) % 200 + (40 if dark else 0)
        return f"Color.FromRgb({base}, {(base * 3) % 256}, {(base * 7) % 256})"
    if kind == "double":
        return f"{i + (2 if dark else 1)}"
    if kind == "Thickness":
        return f"new Thickness({i % 8 + 4}, {i % 4})"
    if kind == "CornerRadius":
        return f"new CornerRadius({i % 12 + 4})"
    if kind == "BoxShadows":
        return f'BoxShadows.Parse("0 {i % 4 + 1} {i % 8 + 4} 0 #{"66" if dark else "1A"}000000")'
    if kind == "FontFamily":
        return 'FontFamily.Default'
    if kind == "FontWeight":
        return "FontWeight.Medium"
    if kind == "TimeSpan":
        return f"TimeSpan.FromMilliseconds({120 + i * 40})"
    raise ValueError(kind)


def token_class(name, props, is_global):
    lines = [f"[ControlDesignToken{'(IsGlobal = true)' if is_global else ''}]",
             f"internal sealed class {name} : AbstractControlDesignToken", "{"]
    for kind, prop in props:
        default = " = FontFamily.Default;" if kind == "FontFamily" else ""
        lines.append(f"    public {kind} {prop} {{ get; set; }}{default}")
    lines.append("")
    lines.append("    public override void CalculateTokenValues(bool isDarkMode)")
    lines.append("    {")
    lines.append("        base.CalculateTokenValues(isDarkMode);")
    if is_global:
        lines.append("        var seed = EffectiveGlobalToken.ColorPrimary;")
    lines.append("        if (isDarkMode)")
    lines.append("        {")
    for i, (kind, prop) in enumerate(props):
        lines.append(f"            {prop} = {value(kind, i, True)};")
    lines.append("        }")
    lines.append("        else")
    lines.append("        {")
    for i, (kind, prop) in enumerate(props):
        lines.append(f"            {prop} = {value(kind, i, False)};")
    lines.append("        }")
    if is_global:
        lines.append("        Color0 = seed;")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def write_tokens():
    parts = ["// Generated by generate_scale.py; do not edit.",
             "using Avalonia;", "using Avalonia.Controls.Primitives;", "using Avalonia.Media;", "",
             "namespace TKCode.Arc.FoundationAotSample.Scale;", "",
             token_class("ScaleDesignToken", GLOBAL, True), ""]
    for i in range(CONTROL_IDENTITIES):
        parts.append(token_class(f"Scale{i:03}Token", CONTROL, False))
        parts.append("")
    for i in range(THEME_FILES):
        parts.append(f"/// <summary>Scale control {i}.</summary>")
        parts.append(f"public class ScaleControl{i:03} : TemplatedControl")
        parts.append("{")
        parts.append("}")
        parts.append("")
    parts.append("/// <summary>Creates scale controls by index without reflection.</summary>")
    parts.append("public static class ScaleControls")
    parts.append("{")
    parts.append("    /// <summary>Creates control <paramref name=\"index\"/>.</summary>")
    parts.append("    public static TemplatedControl Create(int index) => index switch")
    parts.append("    {")
    for i in range(THEME_FILES):
        parts.append(f"        {i} => new ScaleControl{i:03}(),")
    parts.append("        _ => throw new System.ArgumentOutOfRangeException(nameof(index))")
    parts.append("    };")
    parts.append("}")
    parts.append("")
    with open(os.path.join(HERE, "Scale", "ScaleTokens.cs"), "w") as f:
        f.write("\n".join(parts))


def theme(i):
    t = i % CONTROL_IDENTITIES
    own = f"Scale{t:03}TokenResource"
    g = "ScaleDesignTokenResource"
    borders = []
    for b in range(6):
        borders.append(
            f'                    <Border Name="PART_Layer{b}" Background="{{arc:{g} Color{(i + b) % 120}}}" '
            f'CornerRadius="{{arc:{own} Radius0}}" Margin="{{arc:{own} Inset{b % 5}}}" '
            f'Padding="{{arc:{own} Inset{(b + 1) % 5}}}" />')
    return f"""<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    xmlns:arc="https://github.com/AIDotNet/TKCode.Arc"
                    x:Class="TKCode.Arc.FoundationAotSample.Scale.ScaleControl{i:03}Theme"
                    x:ClassModifier="internal">
    <ControlTheme x:Key="{{x:Type arc:ScaleControl{i:03}}}" TargetType="arc:ScaleControl{i:03}">
        <Setter Property="Background" Value="{{arc:{g} Color{i % 120}}}" />
        <Setter Property="BorderBrush" Value="{{arc:{own} Tint0}}" />
        <Setter Property="Padding" Value="{{arc:{own} Inset0}}" />
        <Setter Property="CornerRadius" Value="{{arc:{g} Radius{i % 10}}}" />
        <Setter Property="MinHeight" Value="{{arc:{own} Size0}}" />
        <Setter Property="Template">
            <ControlTemplate TargetType="arc:ScaleControl{i:03}">
                <Panel>
{chr(10).join(borders)}
                </Panel>
            </ControlTemplate>
        </Setter>
        <Style Selector="^:pointerover">
            <Setter Property="Background" Value="{{arc:{g} Color{(i + 1) % 120}}}" />
        </Style>
    </ControlTheme>
</ResourceDictionary>
"""


def write_themes():
    root = os.path.join(HERE, "Scale")
    for i in range(THEME_FILES):
        directory = os.path.join(root, f"ScaleControl{i:03}", "Themes")
        os.makedirs(directory, exist_ok=True)
        with open(os.path.join(directory, f"ScaleControl{i:03}Theme.axaml"), "w") as f:
            f.write(theme(i))


if __name__ == "__main__":
    os.makedirs(os.path.join(HERE, "Scale"), exist_ok=True)
    write_tokens()
    write_themes()
