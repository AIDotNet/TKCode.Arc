# Generates src/TKCode.Arc.Editor/Core/UnicodeCharacterData.Data.cs from vscode's strings.ts (the JSON blobs of
# AmbiguousCharacters and InvisibleCharacters). Usage: python3 -I generate_unicode_data.py <strings.ts> <output .cs>

import json, re, sys
src = open(sys.argv[1], encoding='utf-8').read()
def grab(after):
    i = src.index(after)
    j = src.index("JSON.parse(", i) + len("JSON.parse(")
    while src[j] in "\n\t ": j += 1
    q = src[j]
    k = j + 1
    out = []
    while True:
        c = src[k]
        if c == '\\':
            out.append(src[k+1]); k += 2; continue
        if c == q: break
        out.append(c); k += 1
    return json.loads(''.join(out))
amb = grab("class AmbiguousCharacters")
inv = grab("class InvisibleCharacters")
def arr(xs, indent):
    lines = []
    for i in range(0, len(xs), 24):
        lines.append(indent + ", ".join(str(x) for x in xs[i:i+24]) + ",")
    return "\n".join(lines)
o = []
o.append("// Generated from vscode (src/vs/base/common/strings.ts: the data of AmbiguousCharacters and InvisibleCharacters, which")
o.append("// upstream generates with https://github.com/hediet/vscode-unicode-data; commit b57d5c9e), MIT license.")
o.append("// Regenerated by tools/editor/generate_unicode_data.py <vscode>/src/vs/base/common/strings.ts <this file>; do not edit by hand.")
o.append("")
o.append("namespace TKCode.Arc.Editor;")
o.append("")
o.append("internal static partial class UnicodeCharacterData")
o.append("{")
o.append("    /// <summary>Per locale (and _common / _default): code point, ASCII code point it can be confused with, ...</summary>")
o.append("    public static readonly (string Locale, int[] Pairs)[] AmbiguousRawData =")
o.append("    [")
for k, v in amb.items():
    o.append(f"        (\"{k}\",")
    o.append("        [")
    o.append(arr(v, "            "))
    o.append("        ]),")
o.append("    ];")
o.append("")
o.append("    /// <summary>The invisible characters (upstream's InvisibleCharacters raw data, flattened).</summary>")
o.append("    public static readonly int[] InvisibleRawData =")
o.append("    [")
flat = []
for v in inv.values():
    flat.extend(v)
o.append(arr(flat, "        "))
o.append("    ];")
o.append("}")
open(sys.argv[2], 'w', encoding='utf-8').write("\n".join(o) + "\n")
print(len(amb), list(amb.keys()), len(flat), 160 in flat)
