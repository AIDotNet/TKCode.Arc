#!/usr/bin/env python3
"""Builds the emoji table of EmojiPicker (src/TKCode.Arc.Special/Inputs/EmojiPicker/Data/emoji.txt).

Sources (both under the Unicode License v3, https://www.unicode.org/license.txt):
  - emoji-test.txt from https://unicode.org/Public/emoji/<version>/emoji-test.txt (groups, order, names, versions,
    skin tone variants);
  - the English CLDR annotations, cldr-json/cldr-annotations-full/annotations/en/annotations.json from
    https://github.com/unicode-org/cldr-json (search keywords).

Usage: python3 -I tools/emoji/generate_emoji.py <emoji-test.txt> <annotations.json> <output emoji.txt>

Output, UTF-8, one line per record:
  # comment lines
  @<group key>                      starts a group (the Component group is left out)
  <emoji>\t<name>\t<keywords>\t<version>\t<tone version>\t<5 tone variants, space separated>
Keywords are lower case and space separated, without the words of the name. Emoji with no skin tones leave the last
two fields empty. Only fully qualified emoji are kept; tone variants with two different tones are left out (the picker
applies one tone to everything).
"""

import json
import re
import sys

GROUP_KEYS = {
    "Smileys & Emotion": "smileys",
    "People & Body": "people",
    "Animals & Nature": "nature",
    "Food & Drink": "food",
    "Travel & Places": "travel",
    "Activities": "activities",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}

TONES = ["light skin tone", "medium-light skin tone", "medium skin tone", "medium-dark skin tone", "dark skin tone"]
TONE_POINTS = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)\s+(.+)$")


def main(test_path, annotations_path, out_path):
    with open(annotations_path, encoding="utf-8") as f:
        annotations = json.load(f)["annotations"]["annotations"]

    groups = []  # (key, [records])
    by_name = {}
    current = None
    version_header = ""
    with open(test_path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if line.startswith("# Version:"):
                version_header = line[len("# Version:"):].strip()
            if line.startswith("# group:"):
                name = line[len("# group:"):].strip()
                key = GROUP_KEYS.get(name)
                current = None if key is None else []
                if key is not None:
                    groups.append((key, current))
                continue
            if current is None:
                continue
            m = LINE.match(line)
            if not m:
                continue
            points = [int(p, 16) for p in m.group(1).split()]
            emoji = "".join(chr(p) for p in points)
            version = m.group(2)
            name = m.group(3).strip()
            if any(p in TONE_POINTS for p in points):
                base, _, tone = name.partition(": ")
                if tone in TONES and base in by_name:
                    record = by_name[base]
                    record["tones"][TONES.index(tone)] = emoji
                    if float(version) > float(record["tone_version"] or "0"):
                        record["tone_version"] = version
                continue
            record = {"emoji": emoji, "name": name, "version": version, "tones": [None] * 5, "tone_version": ""}
            by_name[name] = record
            current.append(record)

    lines = [
        "# EmojiPicker emoji table, generated by tools/emoji/generate_emoji.py.",
        "# Data: Unicode emoji-test.txt " + version_header + " and CLDR English annotations, Unicode License v3,",
        "# Copyright (c) 1991-2024 Unicode, Inc. https://www.unicode.org/license.txt",
    ]
    count = 0
    for key, records in groups:
        lines.append("@" + key)
        for r in records:
            name_words = set(re.findall(r"[a-z0-9]+", r["name"].lower()))
            entry = annotations.get(r["emoji"]) or annotations.get(r["emoji"].replace("️", ""))
            keywords = []
            if entry:
                for k in entry.get("default", []):
                    for w in re.findall(r"[a-z0-9]+", k.lower()):
                        if w not in name_words and w not in keywords:
                            keywords.append(w)
            tones = r["tones"]
            has_tones = all(t is not None for t in tones)
            lines.append("\t".join([
                r["emoji"],
                r["name"],
                " ".join(keywords),
                r["version"],
                r["tone_version"] if has_tones else "",
                " ".join(tones) if has_tones else "",
            ]))
            count += 1
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{count} emoji in {len(groups)} groups -> {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3])
