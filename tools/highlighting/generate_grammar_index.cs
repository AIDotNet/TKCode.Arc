#:property AllowUnsafeBlocks=true
#:property Nullable=enable
// Regenerates src/TKCode.Arc.Highlighting/buildTransitive/TKCode.Arc.Highlighting.Grammars.targets: which embedded
// resources of TextMateSharp.Grammars belong to which grammar folder, and the language ids each folder declares. The
// ArcHighlightLanguages targets use it to drop the grammars an app did not ask for when it is trimmed (ADR 0050).
// Run after StreamMark moves to another TextMateSharp.Grammars version:
//   dotnet run tools/highlighting/generate_grammar_index.cs -- <path to TextMateSharp.Grammars.dll> <output .targets>
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Security;
using System.Text;
using System.Text.Json;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: generate_grammar_index.cs <TextMateSharp.Grammars.dll> <output .targets>");
    return 1;
}

const string Prefix = "TextMateSharp.Grammars.Resources.Grammars.";
var dll = args[0];
var resources = ReadResources(dll);
var version = System.Diagnostics.FileVersionInfo.GetVersionInfo(dll).FileVersion ?? "?";

// folder -> its grammar files (syntaxes) and the language ids its package.json contributes.
var syntaxes = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
var languages = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
foreach (var (name, data) in resources)
{
    if (!name.StartsWith(Prefix, StringComparison.Ordinal))
    {
        continue;
    }
    var rest = name[Prefix.Length..];
    var folder = rest[..rest.IndexOf('.')];
    if (rest.Contains(".syntaxes.", StringComparison.Ordinal))
    {
        Add(syntaxes, folder, name);
    }
    else if (rest == folder + ".package.json")
    {
        Add(languages, folder, folder.ToLowerInvariant());
        using var json = JsonDocument.Parse(data);
        if (json.RootElement.TryGetProperty("contributes", out var contributes)
            && contributes.TryGetProperty("languages", out var list))
        {
            foreach (var language in list.EnumerateArray())
            {
                if (language.TryGetProperty("id", out var id) && id.GetString() is { Length: > 0 } value)
                {
                    Add(languages, folder, value.ToLowerInvariant());
                }
            }
        }
    }
}

var sb = new StringBuilder();
sb.AppendLine("<Project>");
sb.AppendLine($"    <!-- Generated by tools/highlighting/generate_grammar_index.cs from TextMateSharp.Grammars {version}; do not edit.");
sb.AppendLine("         _ArcHighlightGrammarLanguage: a name ArcHighlightLanguages accepts (a folder or a language id it declares).");
sb.AppendLine("         _ArcHighlightGrammarResource: a grammar file of that folder, removed from a trimmed app that does not list it. -->");
sb.AppendLine("    <ItemGroup>");
foreach (var (folder, ids) in languages)
{
    if (!syntaxes.ContainsKey(folder))
    {
        continue;
    }
    foreach (var id in ids)
    {
        sb.AppendLine($"        <_ArcHighlightGrammarLanguage Include=\"{SecurityElement.Escape(id)}\" Folder=\"{folder}\" />");
    }
}
foreach (var (folder, files) in syntaxes)
{
    foreach (var file in files)
    {
        sb.AppendLine($"        <_ArcHighlightGrammarResource Include=\"{folder}\" Resource=\"{SecurityElement.Escape(file)}\" />");
    }
}
sb.AppendLine("    </ItemGroup>");
sb.AppendLine("</Project>");
File.WriteAllText(args[1], sb.ToString().Replace("\r\n", "\n"));
Console.WriteLine($"{syntaxes.Count} grammar folders, {syntaxes.Values.Sum(s => s.Count)} grammar files -> {args[1]}");
return 0;

static void Add(SortedDictionary<string, SortedSet<string>> map, string key, string value)
{
    if (!map.TryGetValue(key, out var set))
    {
        map[key] = set = new SortedSet<string>(StringComparer.Ordinal);
    }
    set.Add(value);
}

static unsafe List<(string Name, byte[] Data)> ReadResources(string path)
{
    using var stream = File.OpenRead(path);
    using var pe = new PEReader(stream);
    var metadata = pe.GetMetadataReader();
    var block = pe.GetSectionData(pe.PEHeaders.CorHeader!.ResourcesDirectory.RelativeVirtualAddress);
    var list = new List<(string, byte[])>();
    foreach (var handle in metadata.ManifestResources)
    {
        var resource = metadata.GetManifestResource(handle);
        if (!resource.Implementation.IsNil)
        {
            continue;
        }
        var start = block.Pointer + resource.Offset;
        var length = *(int*)start;
        list.Add((metadata.GetString(resource.Name), new ReadOnlySpan<byte>(start + 4, length).ToArray()));
    }
    return list;
}
