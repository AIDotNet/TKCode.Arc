# Regenerates src/TKCode.Arc.Themes.Pixel/PixelRadiusTable.g.cs: every CornerRadius control token of the Arc packages.
# Input: the generated GeneratedThemeBuildContracts.g.cs files under src/*/GeneratedFiles (exist after a build).
import glob, os, re, collections

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "..", "src")
pattern = re.compile(r'ThemeBuildTokenAttribute\(1, "([^"]*)", "([^"]*)", "([^"]*)", "global::Avalonia\.CornerRadius"')
found = collections.defaultdict(lambda: collections.defaultdict(set))
for path in glob.glob(os.path.join(src, "*", "GeneratedFiles", "AtomUI.Generator", "*", "GeneratedThemeBuildContracts.g.cs")):
    for catalog, control, token in pattern.findall(open(path, encoding="utf-8-sig").read()):
        if control != "ArcDesign":
            found[catalog][control].add(token)

names = {
    "TKCode.Arc": "Controls",
    "TKCode.Arc.Blocks": "Blocks",
    "TKCode.Arc.Special": "Special",
    "TKCode.Arc.AdvancedCharts": "AdvancedCharts",
    "TKCode.Arc.Workflow": "Workflow",
}
out = ["// <auto-generated by tools/pixel/generate_pixel_radii.py; do not edit.", "namespace TKCode.Arc.Themes.Pixel;", "",
       "internal static class PixelRadiusTable", "{"]
for catalog, field in names.items():
    out.append(f"    internal static readonly (string Control, string[] Tokens)[] {field} =")
    out.append("    [")
    for control in sorted(found[catalog]):
        toks = ", ".join(f'"{t}"' for t in sorted(found[catalog][control]))
        out.append(f'        ("{control}", [{toks}]),')
    out.append("    ];")
    out.append("")
out.append("}")
open(os.path.join(src, "TKCode.Arc.Themes.Pixel", "PixelRadiusTable.g.cs"), "w", encoding="utf-8").write("\n".join(out) + "\n")
